// Writes one static landing page per entry in pages.config.mjs, plus
// public/sitemap.xml. Run with `npm run build:pages` after editing the config.

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PAGES, SITE_ORIGIN } from './pages.config.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const escapeHtml = (value) =>
  String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const pageUrl = (page) => `${SITE_ORIGIN}/${page.slug}`;

function render(page) {
  const t = escapeHtml(page.title);
  const d = escapeHtml(page.description);
  const brand = escapeHtml(page.brand);
  const others = PAGES.filter((entry) => entry.slug !== page.slug)
    .map((entry) => `<a href="/${entry.slug}">SLOTH as a ${escapeHtml(entry.brand)} alternative</a>`)
    .join('\n        ');

  return `<!doctype html>
<!-- Generated by scripts/generate-pages.mjs. Edit scripts/pages.config.mjs instead. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${t}</title>
    <meta name="description" content="${d}" />
    <link rel="canonical" href="${pageUrl(page)}" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="SLOTH" />
    <meta property="og:title" content="${t}" />
    <meta property="og:description" content="${d}" />
    <meta property="og:url" content="${pageUrl(page)}" />
    <meta property="og:image" content="${SITE_ORIGIN}/sloth-thumbnail.jpg" />
    <meta name="twitter:card" content="summary_large_image" />
    <link rel="icon" type="image/png" href="/favicon.png" />
    <link rel="stylesheet" href="/src/home.css" />
  </head>
  <body>
    <main class="home">
      <header class="hero">
        <a href="/"><img class="hero-logo" src="/slothbg.png" alt="SLOTH home" width="440" height="283" /></a>
        <h1>${escapeHtml(page.heading)}</h1>
        <p class="lede">${escapeHtml(page.lede)}</p>
        <a class="cta" href="/app">Open SLOTH</a>
      </header>

      <section class="prose">
        <h2>What SLOTH offers</h2>
        <ul>
          <li>Slides and surveys live together in one markdown file.</li>
          <li>Four question types: single choice, multiple choice, rating from 1 to 5 and free text.</li>
          <li>Your audience opens a link in a browser and follows your slides as you present.</li>
          <li>Responses are saved as a CSV file inside your browser tab, ready to download.</li>
          <li>Slides can run Node.js code during your talk.</li>
          <li>SLOTH is free to use.</li>
        </ul>
      </section>

      <section class="prose">
        <h2>How to run a survey with SLOTH</h2>
        <ol>
          <li>Open SLOTH and choose New to start a deck, or Upload to bring in a markdown file.</li>
          <li>Choose Survey, add your questions and add the survey to your deck.</li>
          <li>Choose Present and share the link with your audience.</li>
          <li>Choose Download to save your project, with the responses as CSV, in a zip file.</li>
        </ol>
      </section>

      <section class="prose">
        <h2>Where ${brand} may suit you better</h2>
        <p>${escapeHtml(page.fit)}</p>
      </section>

      <section class="local">
        <h2>Runs on your device</h2>
        <p>
          SLOTH runs a Node.js process inside your browser tab through
          <a href="https://browserpod.io">BrowserPod</a>. Your decks, files and survey responses
          stay in the tab until you download them.
        </p>
        <a class="cta" href="/app">Open SLOTH</a>
      </section>

      <footer class="foot">
        <a href="/">SLOTH home</a>
        ${others}
        <a href="https://browserpod.io">Powered by BrowserPod</a>
        <p class="foot-note">${brand} is a trademark of its owner. SLOTH is an independent project.</p>
      </footer>
    </main>
  </body>
</html>
`;
}

for (const page of PAGES) {
  if (page.title.length > 60) throw new Error(`${page.slug}: title is ${page.title.length} characters (limit 60).`);
  if (page.description.length > 160) throw new Error(`${page.slug}: description is ${page.description.length} characters (limit 160).`);
  await writeFile(path.join(root, `${page.slug}.html`), render(page));
  console.log(`${page.slug}.html  title ${page.title.length}  description ${page.description.length}`);
}

const urls = [`${SITE_ORIGIN}/`, ...PAGES.map(pageUrl)];
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((url) => `  <url><loc>${url}</loc></url>`).join('\n')}
</urlset>
`;
await writeFile(path.join(root, 'public', 'sitemap.xml'), sitemap);
console.log(`sitemap.xml  ${urls.length} addresses`);
